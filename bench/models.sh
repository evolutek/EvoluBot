#!/usr/bin/env bash
# Writes providers.yaml: every text model of the club's OmniRoute connections, one entry per distinct model.
# /v1/models lists the whole OmniRoute catalogue whatever the key, so the connections are named here.
set -euo pipefail
: "${OMNIROUTE_URL:?set OMNIROUTE_URL, e.g. http://127.0.0.1:20128/v1}"
: "${OMNIROUTE_BENCH_KEY:?set OMNIROUTE_BENCH_KEY}"
cd "$(dirname "$0")"

curl -fsS -H "Authorization: Bearer $OMNIROUTE_BENCH_KEY" "$OMNIROUTE_URL/models" \
  | jq -r '.data[].id' | sort -u \
  | grep -E '^(groq|zai-api|cloudflare-ai|mistral)/|^openrouter/.*:free$' \
  | grep -vE 'whisper|safeguard|flux|embed|moderation|ocr|voxtral|fim|glm-4-32b' \
  | grep -vE '^mistral/(codestral-latest|ministral-[0-9]+b-latest|mistral-small-latest|mistral-large-4-0|mistral-medium|mistral-medium-latest|mistral-medium-3\.5|labs-leanstral-1-5|mistral-vibe-cli-(with-tools|fast))$' \
  | awk '
      BEGIN { print "# Generated by models.sh; edit the filters there, not this list." }
      {
        print "- id: ../../lib/omniroute.js"
        print "  label: " $0
        print "  config:"
        print "    model: " $0
      }' > providers.yaml
echo "providers.yaml: $(grep -c '^- id:' providers.yaml) models"
