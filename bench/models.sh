#!/usr/bin/env bash
# Writes providers.yaml from the models the bench key can reach through OmniRoute.
set -euo pipefail
: "${OMNIROUTE_URL:?set OMNIROUTE_URL, e.g. http://127.0.0.1:20128/v1}"
: "${OMNIROUTE_BENCH_KEY:?set OMNIROUTE_BENCH_KEY}"
cd "$(dirname "$0")"

curl -fsS -H "Authorization: Bearer $OMNIROUTE_BENCH_KEY" "$OMNIROUTE_URL/models" \
  | jq -r '.data[].id' | sort -u \
  | awk -v url="$OMNIROUTE_URL" '
      BEGIN { print "# Generated by models.sh; edit the list, not the format." }
      {
        print "- id: openai:chat:" $0
        print "  label: " $0
        print "  config:"
        print "    apiBaseUrl: " url
        print "    apiKeyEnvar: OMNIROUTE_BENCH_KEY"
        print "    temperature: 0"
        print "    showThinking: false"
      }' > providers.yaml
echo "providers.yaml: $(grep -c '^- id:' providers.yaml) models"
